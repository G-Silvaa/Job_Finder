/**
 * Cargos claramente de desenvolvimento: valem mesmo que o nome do time pareça de outra área
 * ("Software Engineer, Financial Engineering", "Desenvolvedor Back End (Serviços Financeiros)").
 */
const STRONG_DEV = rx(
  [
    'software\\s(?:engineers?|developers?|development\\sengineers?)',
    'swes?',
    '(?:front|back)[\\s-]?end(?:\\s(?:engineers?|developers?|dev))?',
    'full[\\s-]?stack',
    'desenvolvedor(?:a|es)?\\s(?:de\\s)?(?:software|sistemas|web|front|back|full|mobile|java|python|node|react|\\.net|php|ios|android)',
    'engenheir[oa]s?\\sde\\ssoftware',
    'programador(?:a|es)?\\s(?:de\\s)?(?:software|sistemas|web|java|python|php|\\.net|front|back|full)',
    '(?:ios|android|mobile|web|platform|infrastructure|ml|ai|data)\\s(?:engineers?|developers?)',
    '(?:java|python|golang|go|node(?:\\.?js)?|react|ruby|rails|php|\\.net|c#|kotlin|swift|flutter|rust|scala|elixir|typescript|javascript)\\s(?:engineers?|developers?|devs?)',
  ].join('|'),
);

/** Mesmo com "engineer"/"desenvolvedor" no título, estes nunca são de dev. */
const HARD_NON_DEV = rx(
  'sales\\sengineer|solutions?\\s(?:engineer|consultant)|pre[\\s-]?(?:sales|vendas)|support\\sengineer|customer\\sengineer|field\\sengineer|desenvolvedor(?:a)?\\sde\\s(?:negocios|mercado|novos\\snegocios|parcerias|canais|vendas|relacionamento|produtos?|material|conteudo|cursos?|treinamentos?|pessoas|talentos|lideres)|business\\sdevelopment|recruit(?:er|ing|ment)|recrutador(?:a)?|account\\s(?:executive|manager)|banco\\sde\\stalentos|talent\\spool|programador(?:a)?\\s(?:de\\s)?(?:pcp|producao|manutencao|cnc|torno)',
);

/**
 * Decide se a vaga é de desenvolvimento de software.
 * `trusted` = a fonte já filtra só vagas de programação (aí só descartamos os falsos positivos óbvios).
 */
export function isDevJob(titleNorm: string, trusted: boolean): boolean {
  if (!titleNorm.trim()) return false;
  if (test(HARD_NON_DEV, titleNorm)) return false;
  if (test(STRONG_DEV, titleNorm)) return true;
  if (test(NON_DEV_TITLE, titleNorm)) return false;
  return trusted || test(DEV_TITLE, titleNorm);
}
